import 'package:flutter/foundation.dart';

/// Реестр сбросов состояния, принадлежащего вошедшему аккаунту.
///
/// Провайдеры живут в `MultiProvider` в `main.dart` и переживают выход из
/// аккаунта. До этого реестра выход чистил один `AuthProvider`, и следующему
/// вошедшему первые секунды показывалось устаревшее: очередь, вердикты по
/// полям, фильтры, раскрытая строка журнала — всё прежнего оператора. Данные
/// платформенные, утечки ПДн здесь нет; дефект в другом: устаревшее выдаётся
/// за текущее ровно в момент входа, когда доверия к экрану больше всего.
/// Со вторым аккаунтом панели (роль «только просмотр», SDL CAT-C-2.11) это
/// становится наблюдаемым при каждом переключении.
///
/// Устройство скопировано с mobile (`mobile/lib/services/account_scope.dart`,
/// фикс `1578b65`): провайдер регистрирует свой сброс один раз в конструкторе,
/// слой авторизации зовёт [resetAll] при выходе, при истёкшей сессии и при
/// входе под другим аккаунтом. Сторож состава —
/// `test/config/account_scope_guard_test.dart`.
class AccountScope {
  AccountScope._();

  static final List<VoidCallback> _resets = [];

  /// Провайдеры живут весь запуск приложения — пути «снять регистрацию» нет.
  static void register(VoidCallback reset) => _resets.add(reset);

  static void resetAll() {
    for (final reset in _resets) {
      reset();
    }
  }

  /// Только для изоляции тестов — забыть всё зарегистрированное.
  @visibleForTesting
  static void debugReset() => _resets.clear();

  /// Сколько сбросов зарегистрировано — для сквозного сторожа.
  ///
  /// Реестр молчалив по устройству: провайдер, забывший про [register], не
  /// меняет ни строчки вывода прогона, а после смены аккаунта показывает
  /// данные прежнего. Сторож обязан уметь пересчитать подписчиков, иначе он
  /// проверяет только сам себя.
  @visibleForTesting
  static int get debugRegisteredCount => _resets.length;
}
